package build

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
	"time"

	"github.com/Scarsz/serverpack/internal/pack"
)

func loadPack(t *testing.T, manifest string) *pack.Pack {
	t.Helper()
	root := t.TempDir()
	dir := filepath.Join(root, "servers", "plot251")
	os.MkdirAll(dir, 0o755)
	manifest = "[server]\nsource = \"papermc\"\nversion = \"1.21.10\"\n" + manifest
	os.WriteFile(filepath.Join(dir, "server.toml"), []byte(manifest), 0o644)
	p, err := pack.Load(root, "plot251")
	if err != nil {
		t.Fatal(err)
	}
	return p
}

func fixedNow() time.Time { return time.Date(2026, 10, 9, 12, 0, 0, 0, time.UTC) }

func TestImageRefs(t *testing.T) {
	p := loadPack(t, `
[build]
images = ["registry.example.com/plots/{name}", "ghcr.io/scarsz/plot251"]
tags = ["latest", "{mc_version}", "{date}"]
`)
	v := newVars(p, fixedNow)
	refs, err := ImageRefs(p, nil, nil, v)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"registry.example.com/plots/plot251:latest",
		"registry.example.com/plots/plot251:1.21.10",
		"registry.example.com/plots/plot251:20261009",
		"ghcr.io/scarsz/plot251:latest",
		"ghcr.io/scarsz/plot251:1.21.10",
		"ghcr.io/scarsz/plot251:20261009",
	}
	if !slices.Equal(refs, want) {
		t.Errorf("refs = %v", refs)
	}

	refs, err = ImageRefs(p, []string{"localhost:5000/test"}, []string{"dev"}, v)
	if err != nil || !slices.Equal(refs, []string{"localhost:5000/test:dev"}) {
		t.Errorf("override refs = %v, %v", refs, err)
	}
	if _, err := ImageRefs(p, []string{"x:tag"}, nil, v); err == nil {
		t.Error("expected error for image with tag")
	}
	if _, err := ImageRefs(p, nil, []string{"{nope}"}, v); err == nil {
		t.Error("expected unknown placeholder error")
	}
}

func TestImageRefsDefaults(t *testing.T) {
	p := loadPack(t, "")
	refs, err := ImageRefs(p, nil, nil, newVars(p, fixedNow))
	if err != nil || !slices.Equal(refs, []string{"plot251:latest"}) {
		t.Errorf("refs = %v, %v", refs, err)
	}
}

func TestDockerfileGolden(t *testing.T) {
	got := Dockerfile(DockerfileOptions{Name: "plot251", BaseImage: "eclipse-temurin:25", ServerpackImage: "ghcr.io/scarsz/serverpack:v1.0.0", MCVersion: "1.21.10", Revision: "abc1234"})
	want := `# syntax=docker/dockerfile:1
# Generated by serverpack dev for plot251. Do not edit; it is regenerated on every build.
FROM eclipse-temurin:25
COPY --from=ghcr.io/scarsz/serverpack:v1.0.0 /serverpack /usr/local/bin/serverpack
# Jars change less often than configs; keep them in their own layer.
COPY jars/ /data/
COPY config/ /data/
WORKDIR /data
LABEL org.opencontainers.image.title="plot251"
LABEL io.serverpack.version="dev"
LABEL io.serverpack.mc-version="1.21.10"
LABEL org.opencontainers.image.revision="abc1234"
ENTRYPOINT ["/usr/local/bin/serverpack", "run"]
`
	if got != want {
		t.Errorf("Dockerfile mismatch:\n%s", got)
	}
	local := Dockerfile(DockerfileOptions{Name: "x", BaseImage: "b", LocalEntrypoint: true})
	if !strings.Contains(local, "COPY --chmod=755 serverpack /usr/local/bin/serverpack") {
		t.Errorf("local entrypoint missing:\n%s", local)
	}
}
