// Package build stages a Docker build context for a pack and runs `docker buildx build`.
package build

import (
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/Scarsz/serverpack/internal/fetch"
	"github.com/Scarsz/serverpack/internal/pack"
	"github.com/Scarsz/serverpack/internal/render"
	"github.com/Scarsz/serverpack/internal/source"
	"github.com/Scarsz/serverpack/internal/srcbuild"
	"github.com/Scarsz/serverpack/internal/version"
)

// DefaultBaseImage is used when [runtime] image is unset.
const DefaultBaseImage = "eclipse-temurin:25"

// Options configure a build.
type Options struct {
	Cache           *fetch.Cache
	Builder         *srcbuild.Builder // builds source = "build" jars
	Images          []string          // override [build] images
	Tags            []string          // override [build] tags
	Platforms       []string          // override [build] platforms
	Push            bool
	EntrypointBin   string // local linux serverpack binary to copy into the image
	ServerpackImage string // image to COPY --from (overrides [build] serverpack_image)
	DryRun          bool   // stage the context and print the docker command, don't run it
	Docker          string
	Stdout, Stderr  io.Writer
	Warn            func(format string, args ...any)
	Now             func() time.Time
}

// Result describes a staged (and possibly built) image.
type Result struct {
	ContextDir string
	Refs       []string
	Command    []string
}

// ContextDir is where a pack's build context is staged.
func ContextDir(p *pack.Pack) string {
	return filepath.Join(p.Root, ".serverpack", "build", p.Self.Name)
}

// Build stages the context and invokes docker.
func Build(ctx context.Context, p *pack.Pack, opts Options) (*Result, error) {
	if opts.Warn == nil {
		opts.Warn = func(string, ...any) {}
	}
	if opts.Docker == "" {
		opts.Docker = "docker"
	}
	if opts.Now == nil {
		opts.Now = time.Now
	}

	vars := newVars(p, opts.Now)
	refs, err := ImageRefs(p, opts.Images, opts.Tags, vars)
	if err != nil {
		return nil, err
	}

	dir := ContextDir(p)
	if err := os.RemoveAll(dir); err != nil {
		return nil, err
	}
	if _, err := render.Render(ctx, p, render.Options{
		Cache:     opts.Cache,
		Builder:   opts.Builder,
		JarsDir:   filepath.Join(dir, "jars"),
		ConfigDir: filepath.Join(dir, "config"),
		Warn:      opts.Warn,
	}); err != nil {
		return nil, err
	}

	df := DockerfileOptions{
		Name:      p.Name,
		BaseImage: p.Manifest.Runtime.Image,
		MCVersion: vars.mcVersion,
	}
	if df.BaseImage == "" {
		df.BaseImage = DefaultBaseImage
	}
	if rev, err := vars.get("git_sha"); err == nil {
		df.Revision = rev
	}
	switch {
	case opts.EntrypointBin != "":
		if err := copyExecutable(opts.EntrypointBin, filepath.Join(dir, "serverpack")); err != nil {
			return nil, fmt.Errorf("entrypoint binary: %w", err)
		}
		df.LocalEntrypoint = true
	default:
		df.ServerpackImage = firstNonEmpty(opts.ServerpackImage, p.Manifest.Build.ServerpackImage, DefaultServerpackImage())
		if version.Version == "dev" && opts.ServerpackImage == "" && p.Manifest.Build.ServerpackImage == "" {
			opts.Warn("this is a dev build of serverpack; the image will use %s. Pass --entrypoint-bin with a linux build to use your local version", df.ServerpackImage)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "Dockerfile"), []byte(Dockerfile(df)), 0o644); err != nil {
		return nil, err
	}

	platforms := p.Manifest.Build.Platforms
	if opts.Platforms != nil {
		platforms = opts.Platforms
	}
	cmd := []string{opts.Docker, "buildx", "build", "--file", filepath.Join(dir, "Dockerfile")}
	for _, r := range refs {
		cmd = append(cmd, "--tag", r)
	}
	if len(platforms) > 0 {
		cmd = append(cmd, "--platform", strings.Join(platforms, ","))
	}
	if opts.Push {
		cmd = append(cmd, "--push")
	} else {
		cmd = append(cmd, "--load")
	}
	cmd = append(cmd, dir)

	res := &Result{ContextDir: dir, Refs: refs, Command: cmd}
	if opts.DryRun {
		return res, nil
	}
	c := exec.CommandContext(ctx, cmd[0], cmd[1:]...)
	c.Stdout, c.Stderr = opts.Stdout, opts.Stderr
	if err := c.Run(); err != nil {
		return res, fmt.Errorf("docker buildx build: %w", err)
	}
	return res, nil
}

// DefaultServerpackImage is the published image containing the serverpack binary for this version.
func DefaultServerpackImage() string {
	tag := version.Version
	if tag == "dev" {
		tag = "latest"
	}
	return "ghcr.io/scarsz/serverpack:" + tag
}

// DockerfileOptions parameterize the generated Dockerfile.
type DockerfileOptions struct {
	Name            string
	BaseImage       string
	ServerpackImage string
	LocalEntrypoint bool
	MCVersion       string
	Revision        string
}

// Dockerfile renders the generated Dockerfile.
func Dockerfile(o DockerfileOptions) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# syntax=docker/dockerfile:1\n")
	fmt.Fprintf(&b, "# Generated by serverpack %s for %s. Do not edit; it is regenerated on every build.\n", version.Version, o.Name)
	fmt.Fprintf(&b, "FROM %s\n", o.BaseImage)
	if o.LocalEntrypoint {
		fmt.Fprintf(&b, "COPY --chmod=755 serverpack /usr/local/bin/serverpack\n")
	} else {
		fmt.Fprintf(&b, "COPY --from=%s /serverpack /usr/local/bin/serverpack\n", o.ServerpackImage)
	}
	fmt.Fprintf(&b, "# Jars change less often than configs; keep them in their own layer.\n")
	fmt.Fprintf(&b, "COPY jars/ /data/\n")
	fmt.Fprintf(&b, "COPY config/ /data/\n")
	fmt.Fprintf(&b, "WORKDIR /data\n")
	labels := [][2]string{
		{"org.opencontainers.image.title", o.Name},
		{"io.serverpack.version", version.Version},
	}
	if o.MCVersion != "" {
		labels = append(labels, [2]string{"io.serverpack.mc-version", o.MCVersion})
	}
	if o.Revision != "" {
		labels = append(labels, [2]string{"org.opencontainers.image.revision", o.Revision})
	}
	for _, l := range labels {
		fmt.Fprintf(&b, "LABEL %s=%s\n", l[0], strconv.Quote(l[1]))
	}
	fmt.Fprintf(&b, "ENTRYPOINT [\"/usr/local/bin/serverpack\", \"run\"]\n")
	return b.String()
}

// vars lazily computes {placeholder} values.
type vars struct {
	p         *pack.Pack
	now       func() time.Time
	mcVersion string
	cache     map[string]string
}

func newVars(p *pack.Pack, now func() time.Time) *vars {
	v := &vars{p: p, now: now, cache: map[string]string{}}
	if srv := p.Server(); srv != nil {
		v.mcVersion, _ = source.ServerContext(srv.Desc)
	}
	return v
}

func (v *vars) get(name string) (string, error) {
	if s, ok := v.cache[name]; ok {
		return s, nil
	}
	var s string
	switch name {
	case "name":
		s = v.p.Name
	case "mc_version":
		if v.mcVersion == "" {
			return "", fmt.Errorf("{mc_version}: the server's Minecraft version is unknown")
		}
		s = v.mcVersion
	case "date":
		s = v.now().UTC().Format("20060102")
	case "git_sha":
		out, err := exec.Command("git", "-C", v.p.Root, "rev-parse", "--short", "HEAD").Output()
		if err != nil {
			return "", fmt.Errorf("{git_sha}: %s is not a git repository with commits", v.p.Root)
		}
		s = strings.TrimSpace(string(out))
		status, err := exec.Command("git", "-C", v.p.Root, "status", "--porcelain").Output()
		if err == nil && len(strings.TrimSpace(string(status))) > 0 {
			s += "-dirty"
		}
	default:
		return "", fmt.Errorf("unknown placeholder {%s} (known: {name}, {mc_version}, {git_sha}, {date})", name)
	}
	v.cache[name] = s
	return s, nil
}

var placeholderRe = regexp.MustCompile(`\{([a-z_]+)\}`)

func (v *vars) expand(s string) (string, error) {
	var firstErr error
	out := placeholderRe.ReplaceAllStringFunc(s, func(m string) string {
		val, err := v.get(m[1 : len(m)-1])
		if err != nil && firstErr == nil {
			firstErr = err
		}
		return val
	})
	return out, firstErr
}

var tagRe = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$`)

// ImageRefs expands every images × tags combination. Flag overrides replace the configured lists.
func ImageRefs(p *pack.Pack, images, tags []string, v *vars) ([]string, error) {
	if images == nil {
		images = p.Manifest.Build.Images
	}
	if tags == nil {
		tags = p.Manifest.Build.Tags
	}
	if len(images) == 0 {
		images = []string{"{name}"}
	}
	if len(tags) == 0 {
		tags = []string{"latest"}
	}
	var refs []string
	for _, img := range images {
		img, err := v.expand(img)
		if err != nil {
			return nil, err
		}
		if strings.Contains(img[strings.LastIndex(img, "/")+1:], ":") {
			return nil, fmt.Errorf("image %q must not include a tag; use [build] tags", img)
		}
		for _, tag := range tags {
			tag, err := v.expand(tag)
			if err != nil {
				return nil, err
			}
			if !tagRe.MatchString(tag) {
				return nil, fmt.Errorf("invalid image tag %q", tag)
			}
			if ref := img + ":" + tag; !slices.Contains(refs, ref) {
				refs = append(refs, ref)
			}
		}
	}
	return refs, nil
}

func copyExecutable(src, dst string) error {
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if len(data) < 4 || string(data[:4]) != "\x7fELF" {
		return fmt.Errorf("%s is not a Linux binary; build one with: CGO_ENABLED=0 GOOS=linux go build -o serverpack-linux .", src)
	}
	return os.WriteFile(dst, data, 0o755)
}

func firstNonEmpty(vals ...string) string {
	for _, v := range vals {
		if v != "" {
			return v
		}
	}
	return ""
}
